-- Backs two new features: a real, computed "trending" page (never an
-- AI-guessed popularity score) and cross-device watchlist sync via a
-- share-link-style code (no accounts/auth, matching this app's existing
-- "no login" posture -- see ShareWatchlistButton.tsx for the precedent).
--
-- One row per (game, anonymous client, day) a watch-toggle-on actually
-- happened -- deliberately deduped per day per client so one person
-- mashing a toggle, or a page reload re-firing an effect, can't inflate a
-- game's count. client_id is a random id useWatchlist.ts generates once
-- and keeps in localStorage (src/lib/clientId.ts) -- not a real identity,
-- just enough to dedupe. Trending is computed live (COUNT(DISTINCT
-- client_id) over a recent window) at request time in
-- worker/routes/trending.ts, not on a cron tick -- this app's five cron
-- trigger slots are already fully allocated (see worker/index.ts's own
-- comment on the 5-trigger cap), and a GROUP BY over this table is cheap
-- at this catalog's scale.
CREATE TABLE watch_events (
  game_id TEXT NOT NULL,
  client_id TEXT NOT NULL,
  day TEXT NOT NULL,
  PRIMARY KEY (game_id, client_id, day)
);

CREATE INDEX idx_watch_events_day ON watch_events(day);

-- code is a random, unguessable (not sequential) string generated by
-- worker/routes/watchlistSync.ts on first push from a device -- same
-- "unauthenticated but unguessable" model as a share link, appropriate
-- here since the payload is just a list of game ids someone is tracking,
-- not sensitive data. game_ids is a JSON array of Game.id strings, fully
-- overwritten on every push (last-write-wins, no merge/history) -- the
-- client is expected to merge locally before pushing if it wants to keep
-- what's already on the code.
CREATE TABLE watchlist_sync (
  code TEXT PRIMARY KEY,
  game_ids TEXT NOT NULL,
  updated_at INTEGER NOT NULL
);
